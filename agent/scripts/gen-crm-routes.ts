import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'

// Rebuilds agent/agentic/crm-routes.ts, the list of the CRM's own /v1/org routes that crm_catalog, crm_query and crm_write check a path
// against, from the CRM's route file. The list is read from that file, never copied from an older tool, so run it again when the CRM adds a route:
//   node agent/scripts/gen-crm-routes.ts <path to sam-crm-be>
// The file it writes says which CRM commit it was read at (and whether the route file had uncommitted changes).

const root = process.argv[2]
if (!root) throw new Error('Usage: node agent/scripts/gen-crm-routes.ts <path to sam-crm-be>')
const file = path.join(root, 'routes', 'orgRoutes.js')
const source = fs.readFileSync(file, 'utf8')

const routes: string[] = []
const lines = source.split('\n')
for (let i = 0; i < lines.length; i++) {
  const m = /^router\.(get|post|put|patch|delete)\(\s*(["'`])([^"'`]+)\2/.exec(lines[i].trim())
  if (!m) continue
  // The route file's own "/:id" (the host's module catalogue for its health check) is not a thing in the CRM to read or change.
  if (m[3].startsWith('/:')) continue
  const route = `${m[1].toUpperCase()} ${m[3]}`
  if (!routes.includes(route)) routes.push(route)
}
if (routes.length < 100) throw new Error(`Only ${routes.length} routes found in ${file}: the file has changed shape, check this script`)

const git = (...args: string[]) => execFileSync('git', ['-C', root, ...args], { encoding: 'utf8' }).trim()
let commit = 'unknown'
let dirty = false
try {
  commit = git('rev-parse', 'HEAD')
  dirty = git('status', '--porcelain', '--', 'routes/orgRoutes.js') !== ''
} catch {
  // not a git checkout: the file still says where it came from
}

const out = [
  '// GENERATED by agent/scripts/gen-crm-routes.ts from sam-crm-be/routes/orgRoutes.js. Do not edit by hand; run the script again instead.',
  `export const CRM_ROUTES_FROM = { commit: '${commit}', routeFileChanged: ${dirty}, generatedOn: '${new Date().toISOString().slice(0, 10)}' } as const`,
  '',
  '/** "METHOD /path" under /v1/org, in the CRM\'s own spelling (":id" is any one segment). */',
  'export const CRM_ROUTES: readonly string[] = [',
  ...routes.map(r => `  '${r}',`),
  ']',
  '',
]
fs.writeFileSync(path.join(import.meta.dirname, '..', 'agentic', 'crm-routes.ts'), out.join('\n'))
console.log(`${routes.length} routes written (CRM commit ${commit.slice(0, 8)}${dirty ? ', route file has uncommitted changes' : ''})`)
